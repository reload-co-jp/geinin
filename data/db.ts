const person = (
  id: string,
  name: string,
  reading: string,
  rest: Partial<Person> = {}
): Person => ({
  id,
  name,
  reading,
  aliases: [],
  agency_id: null,
  debut_date: null,
  birth_date: null,
  training_school: null,
  training_school_term: null,
  biography: null,
  activity_status: null,
  source_ids: ["wiki"],
  ...rest,
})

const group = (
  id: string,
  name: string,
  reading: string,
  rest: Partial<Group> = {}
): Group => ({
  id,
  name,
  reading,
  aliases: [],
  group_type: "combi",
  formation_date: null,
  dissolution_date: null,
  agency_id: null,
  activity_status: null,
  source_ids: ["wiki"],
  ...rest,
})

const member = (
  person_id: string,
  group_id: string,
  rest: Partial<Membership> = {}
): Membership => ({
  person_id,
  group_id,
  role: null,
  start_date: null,
  end_date: null,
  status: "current",
  ...rest,
})

const rel = (
  id: string,
  source_person_id: string,
  target_person_id: string,
  relationship_type: Relationship["relationship_type"],
  description: string,
  rest: Partial<Relationship> = {}
): Relationship => ({
  id,
  source_person_id,
  target_person_id,
  relationship_type,
  description,
  start_date: null,
  end_date: null,
  evidence_type: "encyclopedia",
  confidence: "high",
  source_ids: ["wiki"],
  last_verified_at: null,
  ...rest,
})

